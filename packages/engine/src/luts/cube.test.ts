import { describe, expect } from 'vitest'
import { it } from '@effect/vitest'
import { Arbitrary, Schema } from 'effect'
import { parseCube, LutParseError } from './cube'

// Property tests derive their inputs from Effect Schemas and generate through
// Effect's `Arbitrary` (docs/adr/0012-property-testing). Bounds live in the
// Schema, so a shrinking counterexample is also a valid value of that Schema.

/** A `.cube` size the parser accepts. */
const CubeSize = Schema.Int.check(Schema.isBetween({ minimum: 2, maximum: 8 }))

/** A texel channel: an in-gamut float, already rounded to the float32 the
 *  parser stores, with -0 normalized (the text round-trip prints it as "0"). */
const TexelChannel = Arbitrary.map(
  Arbitrary.schema(Schema.Finite.check(Schema.isBetween({ minimum: 0, maximum: 1 }))),
  (value) => {
    const f32 = Math.fround(value)
    return f32 === 0 ? 0 : f32
  },
)

/** A size plus exactly `size³ × 3` channels, in file point order. */
const cubeArb = Arbitrary.flatMap(Arbitrary.schema(CubeSize), (size) =>
  Arbitrary.map(
    Arbitrary.array(TexelChannel, { maxLength: size ** 3 * 3, minLength: size ** 3 * 3 }),
    (values) => ({ size, values }),
  ),
)

/** Serialize a cube the way real-world exporters do: headers, a comment,
 *  blank lines, CRLF endings, and an extra alpha column per data line. */
const serializeCube = (size: number, values: ReadonlyArray<number>): string =>
  [
    '# generated by property test',
    `TITLE "prop"`,
    `LUT_3D_SIZE ${size}`,
    'DOMAIN_MIN 0.0 0.0 0.0',
    'DOMAIN_MAX 1.0 1.0 1.0',
    '',
    ...Array.from({ length: size ** 3 }, (_, i) => {
      const [r, g, b] = [values[i * 3]!, values[i * 3 + 1]!, values[i * 3 + 2]!]
      // Float32 values print as their shortest exact repr, so a parse
      // round-trip is bit-identical.
      return `${r} ${g} ${b} 1`
    }),
  ].join('\r\n')

/** Text that stays a single line where a `.cube` header interpolates it: a
 *  line terminator would smuggle in an extra, unparsable line. */
const singleLine = (arbitrary: Arbitrary.Arbitrary<string>): Arbitrary.Arbitrary<string> =>
  Arbitrary.filter(arbitrary, (text) => !/[\r\n]/.test(text))

/** A cube whose point values encode their own index — the file-order pin. */
const indexCube = (size: number): string => {
  const lines = [`LUT_3D_SIZE ${size}`]
  for (let i = 0; i < size ** 3; i++) {
    lines.push(`${i} ${i} ${i}`)
  }
  return lines.join('\n')
}

describe('parseCube', () => {
  it.prop(
    'round-trips any generated cube through its own serialization',
    {
      cube: cubeArb,
    },
    ({ cube: { size, values } }) => {
      const cube = parseCube(serializeCube(size, values))
      expect(cube.size).toBe(size)
      expect(cube.data).toHaveLength(size ** 3 * 3)
      for (let i = 0; i < values.length; i++) {
        // The extra alpha column never lands in the data, and float32
        // values survive the text round-trip bit-exactly.
        expect(cube.data[i]).toBe(values[i])
      }
    },
  )

  it.prop(
    'preserves the file point order for any cube size',
    { size: Schema.Int.check(Schema.isBetween({ minimum: 2, maximum: 16 })) },
    ({ size }) => {
      const cube = parseCube(indexCube(size))
      expect(cube.data).toHaveLength(size ** 3 * 3)
      for (let i = 0; i < size ** 3; i++) {
        // Point i is texel (r = i % size, g = (i / size) % size, b = i /
        // size²) in the file's red-fastest order; its value is its index.
        expect(cube.data[i * 3]).toBe(i)
        expect(cube.data[i * 3 + 1]).toBe(i)
        expect(cube.data[i * 3 + 2]).toBe(i)
      }
    },
    // Slow under parallel load (size-16 → 4096 points per run); keep it
    // hermetic, just allow wall-clock headroom.
    { timeout: 30_000, arbitrary: { runs: 20 } },
  )

  it.prop(
    'accepts any layout of ignorable lines around the data',
    {
      comment: singleLine(Arbitrary.schema(Schema.String)),
      size: Schema.Int.check(Schema.isBetween({ minimum: 2, maximum: 4 })),
      title: singleLine(Arbitrary.schema(Schema.String)),
    },
    ({ size, title, comment }) => {
      const points = Array.from({ length: size ** 3 }, (_, i) => `${i / 10} ${i / 20} ${i / 30}`)
      const text = [
        `# ${comment}`,
        `TITLE "${title}"`,
        'DOMAIN_MIN 0.0 0.0 0.0',
        `LUT_3D_SIZE ${size}`,
        'DOMAIN_MAX 1.0 1.0 1.0',
        '',
        ...points,
        '# trailing comment',
      ].join('\n')
      const cube = parseCube(text)
      expect(cube.size).toBe(size)
      expect(cube.data).toHaveLength(size ** 3 * 3)
      for (let i = 0; i < points.length; i++) {
        const [r, g, b] = points[i]!.split(' ').map(Number)
        expect(cube.data[i * 3]).toBeCloseTo(r!, 6)
        expect(cube.data[i * 3 + 1]).toBeCloseTo(g!, 6)
        expect(cube.data[i * 3 + 2]).toBeCloseTo(b!, 6)
      }
    },
  )

  it.prop(
    'fails with LutParseError on any missing size header',
    {
      text: Arbitrary.filter(
        Arbitrary.schema(Schema.String),
        (value) => !value.includes('LUT_3D_SIZE'),
      ),
    },
    ({ text }) => {
      expect(() => parseCube(text)).toThrow(LutParseError)
    },
  )

  it.prop(
    'fails with LutParseError on an invalid size header',
    {
      value: Arbitrary.filter(
        singleLine(Arbitrary.schema(Schema.String.check(Schema.isMinLength(1)))),
        (text) => text.trim() !== '',
      ),
    },
    ({ value }) => {
      expect(() => parseCube(`LUT_3D_SIZE ${value}\n0 0 0\n`)).toThrow(LutParseError)
    },
  )

  it.prop(
    'fails with LutParseError when the data point count is wrong',
    {
      size: Schema.Int.check(Schema.isBetween({ minimum: 2, maximum: 4 })),
      // Any point count that is provably not size³ (max 32 points).
      count: Schema.Int.check(Schema.isBetween({ minimum: 0, maximum: 32 })),
    },
    ({ size, count }) => {
      if (count === size ** 3) {
        return // not a wrong count
      }
      const text = [
        `LUT_3D_SIZE ${size}`,
        ...Array.from({ length: count }, () => '0.5 0.5 0.5'),
      ].join('\n')
      expect(() => parseCube(text)).toThrow(/Expected \d+ data points/)
    },
  )

  it.prop(
    'fails with LutParseError on malformed data lines',
    {
      // Too few columns and non-numeric tokens are malformed; a line with
      // more than three numbers is NOT (extra columns are tolerated).
      lines: Arbitrary.array(Arbitrary.schema(Schema.Literals(['0 0', 'x y z'])), {
        maxLength: 6,
        minLength: 1,
      }),
    },
    ({ lines }) => {
      expect(() => parseCube(`LUT_3D_SIZE 2\n${lines.join('\n')}`)).toThrow(LutParseError)
    },
  )
})
